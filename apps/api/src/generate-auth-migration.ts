import {getMigrations} from "better-auth/db/migration";
import {writeFileSync,mkdirSync} from "node:fs";
import {dirname,resolve,join} from "node:path";
import {fileURLToPath} from "node:url";
import {authOptions} from "./auth.ts";
import {loadLocalConnection,createLocalPool} from "./local-config.ts";
const root=resolve(dirname(fileURLToPath(import.meta.url)),"../../..");
const c=loadLocalConnection(root),pool=createLocalPool(c,c.database,true);
try {
 await pool.query("CREATE SCHEMA IF NOT EXISTS auth");
 const plan=await getMigrations(authOptions(pool,{mode:"development",host:"127.0.0.1",port:3000,baseURL:"http://127.0.0.1:3000",secret:c.authSecret}));
 const sql=await plan.compileMigrations();
 if(!sql.includes('create table'))throw Error("expected_empty_auth_schema");
 const target=join(root,"packages/storage/migrations/001_better_auth.sql");mkdirSync(dirname(target),{recursive:true});
 writeFileSync(target,'-- Generated by pinned Better Auth 1.7.12, reviewed as a versioned migration.\nCREATE SCHEMA IF NOT EXISTS auth;\nSET LOCAL search_path=auth,public;\n'+sql+'\nSET LOCAL search_path=public;\n',{flag:"wx"});
 console.log(JSON.stringify({status:"generated",tables:plan.toBeCreated.map(x=>x.table),path:target}));
}finally{await pool.end();}
