const log = (child.stdout ?? '') + (child.stderr ?? '');
writeFileSync(join(output, 'tests.log'), log);
console.log(log);
const passed = child.status === 0 && !child.error;
writeFileSync(join(output, 'receipt.json'), JSON.stringify({ step: 'PM0-05 / PI-05', status: passed ? 'passed' : 'failed', exitCode: child.status, error: child.error?.code ?? null, node: process.version, completedAt: new Date().toISOString(), limits: ['authored synthetic drafts; no human semantic gold', 'offline fixture Store integration; no model calls or resume parser'] }, null, 2) + '\n');
console.log(JSON.stringify({ status: passed ? 'passed' : 'failed', receipt: join(output, 'receipt.json') }));
process.exitCode = passed ? 0 : 1;
